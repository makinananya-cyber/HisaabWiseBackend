#!/usr/bin/env node
/**
 * Copies the iOS fixture corpus into this repo as the backend's contract reference.
 *
 * Why copy rather than read across repos: a path into a sibling checkout works on one laptop and
 * breaks in CI. Copying with the source commit recorded gives a reproducible reference, and
 * re-running this script is how an iOS-side contract change becomes a visible diff here rather
 * than a silent divergence.
 *
 *   npm run contract:sync            # copy, and report what changed
 *   npm run contract:sync -- --check # exit non-zero if anything differs (for CI)
 *
 * The corpus is the definition of done for the screen slices: each fixture is the exact payload a
 * built, working client already decodes.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iosRepo = path.resolve(repoRoot, '..', 'HisaabWiseIOS');
const fixtureSource = path.join(iosRepo, 'HisaabWise', 'HisaabWise', 'Fixtures', 'Resources');
const endpointSource = path.join(iosRepo, 'HisaabWise', 'HisaabWise', 'Networking', 'Endpoint.swift');
const destination = path.join(repoRoot, 'test', 'contract', 'corpus');
const manifestPath = path.join(destination, 'manifest.json');

const checkOnly = process.argv.includes('--check');

function fail(message) {
  console.error(`contract:sync — ${message}`);
  process.exit(1);
}

if (!existsSync(fixtureSource)) {
  fail(
    `the iOS fixture corpus was not found at ${fixtureSource}.\n` +
      'This script expects HisaabWiseIOS/ as a sibling of this repo. In CI, either check both ' +
      'repos out or rely on the committed corpus under test/contract/corpus/.',
  );
}

/** Every `/v1` path literal the client actually calls — the same source `FixtureCorpusTests` reads. */
function extractEndpointPaths() {
  const swift = readFileSync(endpointSource, 'utf8');
  const paths = new Set();
  for (const match of swift.matchAll(/"(\/v1\/[^"]*)"/g)) paths.add(match[1]);
  for (const match of swift.matchAll(/"(v1\/[^"]*)"/g)) paths.add(`/${match[1]}`);
  return [...paths].sort();
}

function iosCommit() {
  try {
    return execFileSync('git', ['-C', iosRepo, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

const fixtures = readdirSync(fixtureSource)
  .filter((name) => name.endsWith('.json'))
  .sort();

mkdirSync(destination, { recursive: true });

const entries = [];
const changed = [];

for (const name of fixtures) {
  const body = readFileSync(path.join(fixtureSource, name));
  const digest = createHash('sha256').update(body).digest('hex').slice(0, 16);
  const target = path.join(destination, name);

  const existing = existsSync(target) ? readFileSync(target) : undefined;
  if (existing === undefined || !existing.equals(body)) {
    changed.push(name);
    if (!checkOnly) writeFileSync(target, body);
  }

  entries.push({ name, sha256: digest, bytes: body.length });
}

const manifest = {
  note: 'Generated by scripts/sync-contract-corpus.mjs. Do not edit by hand.',
  syncedFromIosCommit: iosCommit(),
  endpointPaths: extractEndpointPaths(),
  fixtures: entries,
};
const serialised = `${JSON.stringify(manifest, null, 2)}\n`;

const manifestExisting = existsSync(manifestPath) ? readFileSync(manifestPath, 'utf8') : undefined;
const manifestChanged = manifestExisting !== serialised;
if (manifestChanged && !checkOnly) writeFileSync(manifestPath, serialised);

if (checkOnly && (changed.length > 0 || manifestChanged)) {
  fail(
    `the committed corpus is stale.\n` +
      (changed.length > 0 ? `  fixtures differing: ${changed.join(', ')}\n` : '') +
      (manifestChanged ? '  the manifest differs (endpoint list or source commit)\n' : '') +
      'Run `npm run contract:sync`, review the diff, and commit it. A change here means the ' +
      'client contract moved.',
  );
}

console.log(
  `contract:sync — ${String(fixtures.length)} fixtures, ` +
    `${String(manifest.endpointPaths.length)} endpoint paths, ` +
    `iOS @ ${manifest.syncedFromIosCommit.slice(0, 7)}` +
    (changed.length > 0 ? ` — updated ${String(changed.length)}` : ' — already current'),
);
